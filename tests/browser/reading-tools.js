async page => {
  const check=(value,message)=>{if(!value)throw Error(message);};
  const context=await page.context().browser().newContext({viewport:{width:1440,height:1000}});
  const test=await context.newPage(),errors=[];
  test.on('pageerror',error=>errors.push(error.message));
  try {
    await test.goto('http://127.0.0.1:4173/index.html');
    await test.waitForFunction(()=>window.noteCloud);
    await test.evaluate(()=>noteCloud.ready);
    check(await test.locator('.topbar #bibleOpen').count()===0,'Duplicate Bible entry remains');
    check(await test.locator('#bibleToolbarOpen').count()===1,'Toolbar Bible entry is missing');
    const defaults={authorInput:'林知夏',sourceInput:'城市观察',dateInput:'2025 年 3 月 19 日',dateHeadingInput:'阅读札记',topicInput:'主题：城市观察',mastheadInput:'纸间读写札记'};
    for(const [id,value] of Object.entries(defaults))check(await test.locator('#'+id).inputValue()===value,'Wrong guide default: '+id);
    await test.locator('#newBtn').click();
    for(const [id,value] of Object.entries(defaults))check(await test.locator('#'+id).inputValue()===value,'Wrong new document default: '+id);
    await test.locator('#titleInput').fill('阅读工具检查');
    await test.locator('[data-view=preview]').click();
    const paper=await test.locator('#paper').innerText();
    for(const value of Object.values(defaults))check(paper.includes(value),'Preview lost metadata: '+value);
    await test.screenshot({path:'output/playwright/reading-preview.png',fullPage:true});
    await test.locator('[data-view=edit]').click();
    await test.locator('#authorInput').fill('自己的作者');
    await test.locator('#sourceInput').fill('自己的来源');
    await test.evaluate(()=>noteApp.save());
    await test.reload();
    await test.waitForFunction(()=>window.noteCloud);
    await test.evaluate(()=>noteCloud.ready);
    check(await test.locator('#authorInput').inputValue()==='自己的作者','Existing custom author was replaced');
    check(await test.locator('#sourceInput').inputValue()==='自己的来源','Existing custom source was replaced');
    await test.locator('#bibleToolbarOpen').click();
    await test.waitForFunction(()=>document.querySelectorAll('#bibleBook option').length>0);
    check(await test.locator('#bibleTestament').inputValue()==='旧约','Initial testament should be Old Testament');
    check(await test.locator('#bibleBook option').count()===39,'Old Testament should have 39 books');
    check(await test.locator('#bibleBook option').first().innerText()==='创世记','Wrong Old Testament first book');
    check(await test.locator('#bibleBook option').last().innerText()==='玛拉基书','Wrong Old Testament last book');
    await test.locator('.verse-row input').first().check();
    await test.locator('#bibleTestament').selectOption('新约');
    check(await test.locator('#bibleBook option').count()===27,'New Testament should have 27 books');
    check(await test.locator('#bibleBook').inputValue()==='马太福音','Wrong New Testament first book');
    await test.locator('.verse-row input').first().check();
    check(await test.locator('#bibleSelectedCount').innerText()==='已选 2 节','Cross-testament selection was lost');
    await test.screenshot({path:'output/playwright/bible-testaments.png'});
    await test.locator('[data-bible-tab=search]').click();
    await test.locator('#bibleQuery').fill('约翰福音');
    await test.locator('#bibleSearchButton').click();
    await test.locator('.verse-row').filter({hasText:/约翰福音 \d+:/}).locator('[data-jump]').first().click();
    check(await test.locator('#bibleTestament').inputValue()==='新约','Search jump did not set New Testament');
    check(await test.locator('#bibleBook').inputValue()==='约翰福音','Search jump did not select correct book');
    await test.locator('[data-bible-tab=search]').click();
    await test.locator('#bibleQuery').fill('创世记');
    await test.locator('#bibleSearchButton').click();
    await test.locator('.verse-row').filter({hasText:/创世记 \d+:/}).locator('[data-jump]').first().click();
    check(await test.locator('#bibleTestament').inputValue()==='旧约','Search jump did not set Old Testament');
    check(await test.locator('#bibleBook').inputValue()==='创世记','Search jump failed across testaments');
    await test.mouse.click(2,2);
    check(!await test.locator('#bibleDialog').isVisible(),'Bible backdrop does not close');
    await test.locator('#bibleToolbarOpen').click();
    check(await test.locator('#bibleSelectedCount').innerText()==='已选 0 节','Closing did not clear selected verses');
    await test.locator('#bibleClose').click();
    const editor=test.locator('.paragraph-text').first();
    await editor.fill('红色粗实线下划线快捷键测试');
    await editor.press('ControlOrMeta+A');
    await editor.press('ControlOrMeta+B');
    await editor.press('ControlOrMeta+U');
    const underline=editor.locator('span[style*="text-decoration: underline"]').first();
    check(await underline.count()>0,'Underline shortcut did not apply styled solid underline');
    const underlineStyle=await underline.evaluate(el=>({line:el.style.textDecorationLine,style:getComputedStyle(el).textDecorationStyle,color:el.style.textDecorationColor,thickness:el.style.textDecorationThickness,offset:el.style.textUnderlineOffset}));
    check(underlineStyle.line==='underline'&&underlineStyle.style==='solid'&&underlineStyle.color==='rgb(183, 53, 48)'&&underlineStyle.thickness==='2px'&&underlineStyle.offset==='4px','Underline shortcut styling differs from red toolbar preset: '+JSON.stringify(underlineStyle));
    check(Number(await editor.evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);walker.nextNode();return getComputedStyle(walker.currentNode.parentElement).fontWeight;}))>=600,'Underline shortcut removed the existing bold format');
    check(await test.evaluate(()=>getSelection().toString())==='红色粗实线下划线快捷键测试','Underline shortcut lost selected text');
    await editor.press('ControlOrMeta+Z');
    check(!await editor.evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);walker.nextNode();return getComputedStyle(walker.currentNode.parentElement).textDecorationLine.split(/\s+/).includes('underline');}),'Undo did not remove the underline operation');
    check(Number(await editor.evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);walker.nextNode();return getComputedStyle(walker.currentNode.parentElement).fontWeight;}))>=600,'Undoing underline removed bold text');
    await editor.press('ControlOrMeta+Shift+Z');
    check(await editor.locator('span[style*="text-decoration: underline"]').count()>0,'Redo did not restore the underline operation');
    await editor.press('ControlOrMeta+A');
    await editor.press('ControlOrMeta+U');
    check(!await editor.evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);walker.nextNode();for(let node=walker.currentNode.parentElement;node&&el.contains(node);node=node.parentElement)if(getComputedStyle(node).textDecorationLine.split(/\s+/).includes('underline'))return true;return false;}),'Ctrl+U did not toggle the red underline off');
    check(Number(await editor.evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);walker.nextNode();return getComputedStyle(walker.currentNode.parentElement).fontWeight;}))>=600,'Removing underline removed the existing bold format');
    check(await test.evaluate(()=>getSelection().toString())==='红色粗实线下划线快捷键测试','Removing underline lost selected text');
    await editor.fill('波浪线快捷键测试');
    await editor.press('ControlOrMeta+A');
    await editor.press('ControlOrMeta+Shift+U');
    check(await editor.locator('span[style*="wavy"]').count()>0,'Wavy underline shortcut did not apply');
    check(await test.evaluate(()=>getSelection().toString())==='波浪线快捷键测试','Shortcut lost selected text');
    await editor.press('ControlOrMeta+Shift+U');
    check(!await editor.evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);walker.nextNode();for(let node=walker.currentNode.parentElement;node&&el.contains(node);node=node.parentElement)if(getComputedStyle(node).textDecorationStyle==='wavy'&&getComputedStyle(node).textDecorationLine.split(/\s+/).includes('underline'))return true;return false;}),'Ctrl+Shift+U did not toggle the red wave off');
    check(await test.evaluate(()=>getSelection().toString())==='波浪线快捷键测试','Removing wave lost selected text');
    await editor.fill('黄色高亮快捷键测试');
    await editor.press('ControlOrMeta+A');
    await editor.press('ControlOrMeta+Shift+H');
    check(await editor.locator('span[style*="background-color"]').count()>0,'Highlight shortcut did not apply yellow highlight');
    await editor.press('ControlOrMeta+Shift+H');
    check(!await editor.evaluate(el=>Array.from(el.querySelectorAll('*')).some(node=>getComputedStyle(node).backgroundColor==='rgb(254, 240, 138)')),'Ctrl+Shift+H did not toggle yellow highlight off');
    check(await test.evaluate(()=>getSelection().toString())==='黄色高亮快捷键测试','Removing highlight lost selected text');
    await editor.fill('重叠标注清除测试');
    await editor.evaluate(el=>{el.innerHTML='<strong><span style="text-decoration:underline 2px #b73530;text-underline-offset:4px"><span style="text-decoration:underline wavy 2px #b73530;text-underline-offset:4px">重叠标注清除测试</span></span></strong>';});
    await editor.click();
    await editor.press('ControlOrMeta+A');
    check(await editor.locator('span').evaluateAll(es=>es.filter(el=>getComputedStyle(el).textDecorationLine.includes('underline')).length)>=2,'Overlapping line styles were not created for clear test');
    await test.locator('[data-palette=wave] > summary').click();
    await test.locator('[data-clear=wave]').click();
    check(!await editor.evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);walker.nextNode();for(let node=walker.currentNode.parentElement;node&&el.contains(node);node=node.parentElement)if(getComputedStyle(node).textDecorationLine.split(/\s+/).includes('underline'))return true;return false;}),'Remove underline/wave did not clear overlapping lines');
    check(await editor.locator('strong').count()>0,'Clearing overlapping lines removed bold text');
    check(await test.evaluate(()=>getSelection().toString())==='重叠标注清除测试','Clearing overlapping lines lost selected text');
    await test.locator('#shortcutsToggle').click();
    await test.locator('#shortcutsSearch').fill('下划线');
    check((await test.locator('.shortcut-row').innerText()).includes('切换红色粗实线下划线'),'Underline shortcut missing in help');
    check((await test.locator('.shortcut-row .shortcut-keys').innerText()).includes('U'),'Wrong underline shortcut keys');
    await test.locator('#shortcutsSearch').fill('波浪线');
    check((await test.locator('.shortcut-row').innerText()).includes('切换红色波浪线'),'Wavy shortcut missing in help');
    check((await test.locator('.shortcut-row .shortcut-keys').innerText()).includes('Shift'),'Wrong wavy shortcut keys');
    await test.locator('#shortcutsSearch').fill('高亮');
    check((await test.locator('.shortcut-row').innerText()).includes('切换黄色高亮'),'Toggle highlight shortcut missing in help');
    await test.screenshot({path:'output/playwright/wavy-shortcut.png'});
    await test.locator('#shortcutsClose').click();
    await test.keyboard.press('ControlOrMeta+Alt+B');
    check(await test.locator('#bibleDialog').isVisible(),'Bible shortcut uses removed entry');
    await test.setViewportSize({width:390,height:844});
    check(await test.locator('#bibleTestament').isVisible(),'Testament picker missing on mobile');
    check(await test.locator('#bibleBook').isVisible(),'Book picker missing on mobile');
    check((await test.locator('#bibleTestament').boundingBox()).width>=80,'Testament label is clipped on mobile');
    check(await test.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile horizontal overflow');
    await test.screenshot({path:'output/playwright/bible-mobile.png'});
    check(!errors.length,'Browser errors: '+errors.join('; '));
    return {passed:true,testaments:{old:39,new:27},defaultsPreserved:true,previewMetadata:true,underlineShortcut:'Ctrl+U red 2px solid',wavyShortcut:'Ctrl+Shift+U',errors};
  } finally { await context.close(); }
}
